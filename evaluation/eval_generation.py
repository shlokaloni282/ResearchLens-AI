"""
Stage 3 — Generation Quality Evaluator for ResearchLens AI.

Evaluates the full RAG pipeline (retrieval → answer generation) against the
ground-truth benchmark in evaluation/data/ground_truth.json.

Metrics computed
----------------
For factoid questions (question_type == "factoid"):
  - Key-Fact Coverage  : fraction of key_facts present in the generated answer
  - Has Citation       : whether the answer includes at least one citation
  - Citation Page Hit  : whether any citation page matches expected_page
  - Has Sufficient Evidence : whether the QA service returned True

For unanswerable questions (question_type == "unanswerable"):
  - Correctly Abstained : has_sufficient_evidence == False

Summary
-------
  - Factoid Accuracy     : mean key_fact coverage across factoid questions
  - Citation Accuracy    : mean citation page hit rate across factoid questions
  - Abstention Rate      : fraction of unanswerable questions correctly abstained

Usage
-----
Prerequisites:
  1. Set GEMINI_API_KEY (or GOOGLE_API_KEY) in your environment for live generation.
     Without a key, answers are generated by MockLLMProvider (always abstains →
     abstention metrics are measured, factoid scores will be 0 by design).
  2. The PDF rng_paper.pdf must exist at data/benchmark_papers/rng_paper.pdf.

Run:
  $env:PYTHONPATH = "."
  $env:GEMINI_API_KEY = "your-key-here"   # optional
  .\.venv\Scripts\python evaluation/eval_generation.py

Output:
  Prints a per-question scorecard to stdout.
  Saves JSON report to evaluation/reports/generation_eval_rng_paper.json.
"""

import asyncio
import json
import os
import re
import sys
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

# ---------------------------------------------------------------------------
# Offline mode — avoids HuggingFace hub network calls during model load
# ---------------------------------------------------------------------------
os.environ.setdefault("HF_HUB_OFFLINE", "1")
os.environ.setdefault("TRANSFORMERS_OFFLINE", "1")

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
PROJECT_ROOT = Path(__file__).resolve().parent.parent
GROUND_TRUTH_PATH = PROJECT_ROOT / "evaluation" / "data" / "ground_truth.json"
PDF_PATH = PROJECT_ROOT / "data" / "benchmark_papers" / "rng_paper.pdf"
REPORTS_DIR = PROJECT_ROOT / "evaluation" / "reports"
REPORT_PATH = REPORTS_DIR / "generation_eval_rng_paper.json"


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def load_ground_truth() -> List[Dict[str, Any]]:
    with open(GROUND_TRUTH_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def normalize(text: str) -> str:
    """Lower-case and collapse whitespace for substring matching."""
    text = text.lower()
    text = re.sub(r"-\s+", "-", text)   # re-join hyphenated line breaks
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def key_fact_coverage(answer: str, key_facts: List[str]) -> float:
    """Return fraction of key_facts found (case-insensitive) in answer text."""
    if not key_facts:
        return 1.0  # vacuously satisfied
    norm_answer = normalize(answer)
    hits = sum(1 for fact in key_facts if normalize(fact) in norm_answer)
    return hits / len(key_facts)


def citation_page_hit(citations: List[Dict], expected_page: Optional[int]) -> bool:
    """Check whether any returned citation page matches the expected page."""
    if expected_page is None:
        return False
    return any(c.get("page_number") == expected_page for c in citations)


# ---------------------------------------------------------------------------
# Index building — uploads the PDF to the in-memory vector index
# ---------------------------------------------------------------------------

def build_index_from_pdf(pdf_path: Path):
    """
    Reads the PDF, chunks it with the 'fixed' strategy (best Hit@1),
    and loads chunks into the default in-memory vector index.
    Returns (paper_id, chunks).
    """
    import fitz
    from uuid import uuid4
    from backend.app.services.chunking import chunk_pages
    from backend.app.services.retrieval import get_default_vector_index

    document = fitz.open(str(pdf_path))
    pages = [
        {"page_number": pno, "text": page.get_text("text")}
        for pno, page in enumerate(document, start=1)
    ]
    document.close()

    paper_id = str(uuid4())
    source_filename = pdf_path.name

    chunks = chunk_pages(
        pages=pages,
        paper_id=paper_id,
        source_filename=source_filename,
        strategy="fixed",
        chunk_size=500,
        overlap=50,
    )

    index = get_default_vector_index()
    index.add_chunks(chunks)
    print(f"  Indexed {len(chunks)} chunks (strategy=fixed) for '{source_filename}'")
    return paper_id, chunks


# ---------------------------------------------------------------------------
# Main evaluation loop
# ---------------------------------------------------------------------------

async def evaluate():
    print("=" * 70)
    print("ResearchLens AI — Stage 3 Generation Quality Evaluator")
    print("=" * 70)

    # --- Check for LLM key ---
    api_key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    if api_key:
        print(f"  LLM: GeminiProvider (key set, model=gemini-1.5-flash)")
        from backend.app.services.qa_service import GeminiProvider, answer_research_question
        llm_provider = GeminiProvider(api_key=api_key)
    else:
        print("  LLM: MockLLMProvider (no API key set — factoid scores will be 0)")
        from backend.app.services.qa_service import MockLLMProvider, answer_research_question
        llm_provider = MockLLMProvider()   # always returns ABSTENTION_MESSAGE

    # --- Load PDF ---
    if not PDF_PATH.exists():
        print(f"\n[ERROR] PDF not found at: {PDF_PATH}")
        print("  Please place rng_paper.pdf in data/benchmark_papers/")
        sys.exit(1)

    print(f"\nBuilding vector index from: {PDF_PATH.name}")
    t0 = time.time()
    paper_id, _ = build_index_from_pdf(PDF_PATH)
    print(f"  Done in {time.time() - t0:.1f}s\n")

    # --- Import answer_research_question (already imported above) ---
    from backend.app.services.qa_service import answer_research_question

    # --- Load ground truth ---
    questions = load_ground_truth()
    print(f"Evaluating {len(questions)} questions from ground_truth.json\n")

    results = []
    factoid_coverages = []
    factoid_citation_hits = []
    abstention_correct = []

    for q in questions:
        qid = q["id"]
        question_text = q["question"]
        qtype = q["question_type"]
        expected_page = q.get("expected_page")
        key_facts = q.get("key_facts", [])

        print(f"  [{qid}] ({qtype}) {question_text[:70]}...")

        t_start = time.time()
        try:
            response = await answer_research_question(
                question=question_text,
                top_k=5,
                source_filename="rng_paper.pdf",
                llm_provider=llm_provider,
            )
        except Exception as exc:
            print(f"    ERROR: {exc}")
            results.append({
                "id": qid,
                "question_type": qtype,
                "error": str(exc),
            })
            continue

        elapsed = time.time() - t_start

        answer = response.answer
        sufficient = response.has_sufficient_evidence
        citations = [c.model_dump() for c in response.citations]

        if qtype == "factoid":
            coverage = key_fact_coverage(answer, key_facts)
            page_hit = citation_page_hit(citations, expected_page)
            factoid_coverages.append(coverage)
            factoid_citation_hits.append(float(page_hit))
            status = f"Coverage={coverage:.0%}  PageHit={'✓' if page_hit else '✗'}  Sufficient={sufficient}"
        else:
            # unanswerable — expect abstention (has_sufficient_evidence=False)
            correctly_abstained = not sufficient
            abstention_correct.append(float(correctly_abstained))
            coverage = None
            page_hit = None
            status = f"Abstained={'✓' if correctly_abstained else '✗ (should abstain)'}  Sufficient={sufficient}"

        print(f"    {status}  [{elapsed:.1f}s]")

        results.append({
            "id": qid,
            "question_type": qtype,
            "question": question_text,
            "answer": answer,
            "has_sufficient_evidence": sufficient,
            "citations": citations,
            "key_facts": key_facts,
            "key_fact_coverage": coverage,
            "citation_page_hit": page_hit,
            "expected_page": expected_page,
            "elapsed_s": round(elapsed, 2),
        })

    # --- Summary ---
    print("\n" + "=" * 70)
    print("GENERATION QUALITY SCORECARD")
    print("=" * 70)

    n_factoid = len(factoid_coverages)
    n_unanswerable = len(abstention_correct)

    if n_factoid > 0:
        mean_coverage = sum(factoid_coverages) / n_factoid
        mean_citation_hit = sum(factoid_citation_hits) / n_factoid
        print(f"  Factoid questions        : {n_factoid}")
        print(f"  Mean Key-Fact Coverage   : {mean_coverage:.1%}")
        print(f"  Mean Citation Page Hit   : {mean_citation_hit:.1%}")
    else:
        mean_coverage = None
        mean_citation_hit = None

    if n_unanswerable > 0:
        abstention_rate = sum(abstention_correct) / n_unanswerable
        print(f"  Unanswerable questions   : {n_unanswerable}")
        print(f"  Abstention Rate          : {abstention_rate:.1%}")
    else:
        abstention_rate = None

    if not api_key:
        print("\n  NOTE: Scores above reflect MockLLMProvider (always abstains).")
        print("  Set GEMINI_API_KEY to evaluate live generation quality.")

    # --- Save report ---
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    report = {
        "eval_type": "generation",
        "llm": "GeminiProvider" if api_key else "MockLLMProvider",
        "strategy": "fixed",
        "n_factoid": n_factoid,
        "n_unanswerable": n_unanswerable,
        "mean_key_fact_coverage": mean_coverage,
        "mean_citation_page_hit": mean_citation_hit,
        "abstention_rate": abstention_rate,
        "questions": results,
    }
    with open(REPORT_PATH, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)
    print(f"\n  Report saved → {REPORT_PATH}")
    print("=" * 70)
    return report


if __name__ == "__main__":
    asyncio.run(evaluate())
