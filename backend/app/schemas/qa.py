from typing import List, Optional
from pydantic import BaseModel, Field


class QuestionRequest(BaseModel):
    """Request model for asking a research question."""
    question: str = Field(
        ...,
        min_length=3,
        description="The research question to be answered from paper context.",
        examples=["What is the power dissipation of the RNG at 100 MHz?"]
    )
    paper_id: Optional[str] = Field(
        default=None,
        description="Optional paper_id to restrict the search to a specific paper."
    )
    source_filename: Optional[str] = Field(
        default=None,
        description="Optional filename to restrict the search to a specific paper file."
    )
    top_k: int = Field(
        default=5,
        ge=1,
        le=20,
        description="Number of top relevant chunks to retrieve as context."
    )


class CitationItem(BaseModel):
    """Citation metadata for a supporting source chunk."""
    source_filename: str = Field(..., description="Name of the source PDF file.")
    page_number: int = Field(..., description="Page number where the evidence appears.")
    chunk_id: Optional[str] = Field(default=None, description="UUID of the supporting chunk.")
    score: Optional[float] = Field(default=None, description="Cosine similarity score of the chunk.")


class AnswerResponse(BaseModel):
    """Response model for an answered research question."""
    question: str = Field(..., description="The original question asked.")
    answer: str = Field(..., description="The grounded answer generated by the LLM.")
    has_sufficient_evidence: bool = Field(
        ...,
        description="Whether sufficient evidence was found in the retrieved chunks."
    )
    citations: List[CitationItem] = Field(
        default_factory=list,
        description="Verified citations with paper and page numbers."
    )
    retrieved_chunks_count: int = Field(
        ...,
        description="Total number of chunks retrieved as context."
    )
